# --- value models -----------------------------------------------------------
#
# Bounds are read inside validators (not at class definition) so the
# `set_option()` deployment overrides in mainsite settings apply.


class PlannedStatusChange(BaseModel):
    """
    Value model for `planned_status_change` (#1742, #1736).

    A pure declaration of intent about the object's `status` field: the key
    is named for the field it targets and speaks that field's value
    vocabulary. Setting or clearing it has no effect on the object's actual
    status, and nothing the object does alters the plan.
    """

    model_config = ConfigDict(extra="forbid")

    status: str
    date: datetime.date

    @field_validator("status")
    @classmethod
    def validate_status(cls, value):
        if value not in PLANNED_STATUS_CHANGE_STATUSES:
            raise ValueError(
                "status must be one of: " + ", ".join(PLANNED_STATUS_CHANGE_STATUSES)
            )
        return value

    @field_validator("date")
    @classmethod
    def validate_date(cls, value, info):
        # The future/window bound is a WRITE-TIME bound: it constrains the
        # moment a plan is set, not the plan's continued validity. It must
        # therefore only be applied to a value the caller is actually
        # writing -- see `validate_meta` for why every write path
        # re-submits an unchanged document, and what re-applying this to
        # such a value would do.
        if not (info.context or {}).get("changed", True):
            return value
        today = datetime.date.today()
        window = settings.META_PLANNED_STATUS_CHANGE_WINDOW_DAYS
        if value <= today:
            raise ValueError("date must be in the future")
        if value > today + datetime.timedelta(days=window):
            raise ValueError(f"date must be at most {window} days ahead")
        return value


def _validate_preferred_ip_mtu(value: int) -> int:
    lo = settings.META_PREFERRED_IP_MTU_MIN
    hi = settings.META_PREFERRED_IP_MTU_MAX
    if not lo <= value <= hi:
        raise ValueError(f"must be between {lo} and {hi}")
    return value


# status values a `planned_status_change` may target on a netixlan:
# "deleted" (the network is leaving the IXP) or "ok" (the connection goes
# live on that date). Read by the value model below and by the UI enum the
# dashboard's select loads -- the registry stays the single source of truth,
# so this vocabulary never needs a django-peeringdb release.
PLANNED_STATUS_CHANGE_STATUSES = ("ok", "deleted")


# standard (16bit:16bit) or large (32bit:32bit:32bit) BGP community.
# [0-9] rather than \d: \d also matches non-ASCII decimal digits, which int()
# happily parses, so "٦٥:٦" would validate and be stored as a
# community string no BGP implementation can parse.
_RTBH_COMMUNITY_REGEX = re.compile(r"^[0-9]{1,10}(:[0-9]{1,10}){1,2}$")


def _validate_rtbh_community(value: str) -> str:
    value = value.strip()
    if not _RTBH_COMMUNITY_REGEX.match(value):
        raise ValueError(
            "must be a BGP community in standard (asn:value) "
            "or large (asn:local1:local2) format"
        )
    parts = [int(part) for part in value.split(":")]
    limit = 0xFFFF if len(parts) == 2 else 0xFFFFFFFF
    if any(part > limit for part in parts):
        raise ValueError(f"community parts must be at most {limit}")
    # canonical form: the key is not filterable, so consumers compare these
    # strings client-side and "065000:0666" must not read as a different
    # community from "65000:666"
    return ":".join(str(part) for part in parts)


# --- registry plumbing ------------------------------------------------------


@dataclass(frozen=True)
class GeneratedColumn:
    """
    A typed, indexed database column derived from the `meta` JSON document.

    Declared on a filterable key; injected into the concrete model by
    `contribute_generated_columns()`. `json_path` addresses into the
    document; `output_field` builds a fresh Django field instance per model
    (field instances cannot be shared across models).
    """

    name: str  # model field / db column name
    json_path: tuple[str, ...]
    output_field: "type[models.Field] | None" = None
    output_field_kwargs: dict = dataclass_field(default_factory=dict)

    def build_field(self):
        # walk the json path: meta -> key -> subkey, unquoting to text
        expression = "meta"
        for path_key in self.json_path:
            expression = KeyTextTransform(path_key, expression)
        output = self.output_field(**self.output_field_kwargs)
        if isinstance(output, models.BooleanField):
            # text-cast of a JSON boolean is the string "true"/"false" --
            # compare against the JSON value instead of casting
            expression = models.Q(**{f"meta__{'__'.join(self.json_path)}": True})
        else:
            expression = Cast(expression, output_field=output)
        return models.GeneratedField(
            expression=expression,
            output_field=output,
            db_persist=True,
            db_index=True,
        )


@dataclass(frozen=True)
class MetaKey:
    """
    A registered metadata key: the registration is the contract.
    """

    name: str
    tags: tuple[str, ...]  # handleref tags this key applies to
    adapter: "type[BaseModel] | _FunctionAdapter"
    columns: tuple[GeneratedColumn, ...] = ()
    # Optional per-key write gate, for a key whose write permission is
    # narrower than "may edit this object" -- none of the launch keys need
    # one, since they are all owner-set voluntary data and the parent
    # endpoint has already enforced the object's normal edit permissions.
    #
    # The callback receives the requesting request, which may be None:
    # `validate_meta` is only ever called from serializer validation, so no
    # production write path arrives without one, but a serializer used
    # without request context does. A permission gate with no identifiable
    # actor DENIES -- write the callback accordingly and do not treat a
    # missing request as an internal-write escape hatch. Code that must set
    # a gated key outside a request writes the model field directly; the
    # model-layer check (`clean_meta`) validates the value but does not
    # apply this gate, since there is no actor to identify there.
    #
    # The gate applies to a *change* of the value, not to its presence in
    # the submitted document: re-submitting the stored value unchanged is
    # not a write of it, and gating that would lock the whole object for
    # anyone who fails the gate.
    writer_check: "Callable[[Request | None], bool] | None" = None

    @property
    def filterable(self):
        return bool(self.columns)

    def validate(self, value, context=None):
        """
        Validate and JSON-normalize one value. Raises ValueError.

        `context` is handed to the value model, which is how write-time
        bounds learn whether this value is actually being written -- see
        `validate_meta`.
        """
        try:
            if isinstance(self.adapter, _FunctionAdapter):
                return self.adapter.validate(value, context=context)
            instance = self.adapter.model_validate(value, context=context)
            return instance.model_dump(mode="json")
        except PydanticValidationError as exc:
            errors = "; ".join(
                "{}: {}".format(
                    ".".join(str(loc) for loc in error["loc"]) or self.name,
                    error["msg"],
                )
                for error in exc.errors()
            )
            raise ValueError(errors)


class _FunctionAdapter:
    """TypeAdapter-alike wrapping a strict base type plus a plain validator."""

    def __init__(self, base_type, func=None):
        self._adapter = TypeAdapter(base_type)
        self._func = func

    def validate(self, value, context=None):
        validated = self._adapter.validate_python(value, context=context)
        if self._func:
            validated = self._func(validated)
        return self._adapter.dump_python(validated, mode="json")


# --- the registry -----------------------------------------------------------

REGISTRY: "dict[str, MetaKey]" = {}


def register(key: MetaKey):
    REGISTRY[key.name] = key
    return key


