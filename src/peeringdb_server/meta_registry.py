"""
Typed key registry for object metadata (#1751).

Objects that participate in the metadata mechanism (net and netixlan at
launch) carry a single `meta` JSON document field, defined once in
django-peeringdb. Everything else lives here, server-side:

- which keys exist, and on which object types (handleref tags)
- each key's value schema and validation (pydantic value models; tunable
  bounds come from deployment settings, never code constants)
- whether a key is filterable: a filterable key declares typed generated
  columns derived from the JSON document. `contribute_generated_columns()`
  injects those columns into the concrete model at import time, so
  `makemigrations` picks them up and the API filter machinery can treat
  them like ordinary indexed fields.

Adding, changing or retiring a key is a change to REGISTRY (plus the
autogenerated migration if the key is filterable) -- no django-peeringdb
release, no API schema event.

Writes with unregistered keys are rejected (`validate_meta`). Metadata is
auxiliary data: registry validation never reads or alters the object's
concrete fields, and planned data is never reconciled with actual state.
"""

