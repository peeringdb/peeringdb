# --- public api -------------------------------------------------------------


def keys_for_tag(tag: str) -> "dict[str, MetaKey]":
    return {name: key for name, key in REGISTRY.items() if tag in key.tags}


def _validate_document(tag: str, meta, *, request=None, current=None, write=True):
    """
    Shared body of `validate_meta` and `clean_meta`: returns
    `(normalized_document, errors)` and never raises for a bad value.
    `errors` is a `{key: message}` dict, or a bare message when the
    document itself is not an object, or None when there is nothing wrong.

    `write` separates the two callers. A write (the API) applies write-time
    bounds and per-key writer gates, both only to the keys whose value
    actually changes. A structural check (the model layer) applies neither:
    it asks only whether the document can be stored, the object's own
    permission check has already happened by then, and re-applying a
    write-time bound to an unchanged value is exactly the lock
    `validate_meta` describes.
    """

    if meta is None:
        return {}, None
    if not isinstance(meta, dict):
        return {}, _("must be an object")

    registered = keys_for_tag(tag)
    errors = {}
    normalized = {}

    for name, value in meta.items():
        key = registered.get(name)
        if key is None:
            errors[name] = _("unregistered metadata key")
            continue
        changed = write and (current is None or current.get(name) != value)
        # the writer gate follows `changed` for the same reason the
        # write-time bounds do (see `validate_meta`): every write path
        # re-submits the whole document, so a key that is merely
        # round-tripped is not being set. Gating it unconditionally would
        # make an object carrying an already-set gated key uneditable by
        # anyone who fails the gate -- not just unwritable for that key.
        if changed and key.writer_check and not key.writer_check(request):
            errors[name] = _("not permitted to set this key")
            continue
        try:
            normalized[name] = key.validate(value, context={"changed": changed})
        except (ValueError, PydanticValidationError) as exc:
            errors[name] = str(exc)

    return normalized, errors or None


def validate_meta(tag: str, meta, request=None, current=None) -> dict:
    """
    Validate a full `meta` document for an object type against the registry.

    Returns the JSON-normalized document. Raises RestValidationError with
    per-key messages; unregistered keys are rejected outright.

    `request` is passed to any key declaring a `writer_check`. It may be
    None (a serializer used without request context), in which case a gated
    key is denied -- see `MetaKey.writer_check`.

    `current` is the object's stored document, when it has one. A key whose
    incoming value is identical to the stored one is not a write of that
    value, so it is exempt from write-time bounds (currently only
    `planned_status_change.date` has one). That exemption is load bearing,
    not a convenience: every write path re-submits the whole document --
    the dashboard exports every field in a netixlan row as soon as one of
    them changes, and an API PUT round-trips `meta` because `meta` is the
    read surface -- so without it, a plan whose date has passed would
    reject every subsequent edit of the object, and since the window is
    finite every plan eventually reaches that state. A plan is a
    declaration that persists until the network edits it (#1742), not a
    lock on the row.
    """

    normalized, errors = _validate_document(
        tag, meta, request=request, current=current, write=True
    )
    if errors:
        raise RestValidationError({"meta": errors})

    return normalized


def clean_meta(tag: str, meta) -> "tuple[dict, dict | str | None]":
    """
    Registry validation for the model layer -- `full_clean()`, and through
    it the Django admin (where `meta` is a free-text JSON box) and
    management commands.

    Returns `(normalized_document, errors)` -- errors being a
    `{key: message}` dict (or a bare message for a non-object document, or
    None when the document is clean), leaving the caller to raise its own
    ValidationError flavor. Same split as `clean_ixp_update_exclude()` in
    validators.py.

    Write-time bounds and per-key writer gates are NOT applied here. This
    runs on every save, including the IX-F importer's, where the document is
    usually untouched; applying the bounds would recreate exactly the lock
    `validate_meta` describes, and applying the gates would make a gated key
    unsavable outside a request. The serializers own both, because they are
    the only layer that knows what changed and who is asking.
    """

    return _validate_document(tag, meta, write=False)


def contribute_generated_columns(model_cls, tag: str):
    """
    Inject the generated columns for all filterable keys registered on
    `tag` into a concrete model. Called at the bottom of the model's class
    definition in models.py; picked up by makemigrations from there.
    """

    for key in keys_for_tag(tag).values():
        for column in key.columns:
            model_cls.add_to_class(column.name, column.build_field())


def filter_column_map(tag: str) -> "dict[str, str]":
    """
    Maps public API filter prefixes (`meta__<path>`) onto the generated
    column names, for the serializer query-param rewrite.
    """

    mapping = {}
    for key in keys_for_tag(tag).values():
        for column in key.columns:
            mapping["meta__" + "__".join(column.json_path)] = column.name
    return mapping


# --- registry <-> schema drift check ----------------------------------------

# handleref tag -> concrete model participating in the metadata mechanism
PARTICIPATING_MODELS = {
    "netixlan": ("peeringdb_server", "NetworkIXLan"),
    "net": ("peeringdb_server", "Network"),
}


def check_meta_registry(app_configs, **kwargs):
    """
    System check: the registry and the model schema must agree.

    Every generated column a registered key declares must exist on its
    model, and every `meta_`-prefixed model field must be declared by the
    registry (a retired key must take its column's removal migration with
    it). Model <-> database drift is covered by `makemigrations --check`
    in CI; together the two make registry drift fail loudly.
    """

    errors = []

    for tag, (app_label, model_name) in PARTICIPATING_MODELS.items():
        model = django_apps.get_model(app_label, model_name)
        model_fields = {field.name for field in model._meta.get_fields()}
        declared = {
            column.name for key in keys_for_tag(tag).values() for column in key.columns
        }

        for name in sorted(declared - model_fields):
            errors.append(
                checks.Error(
                    f"metadata registry declares generated column '{name}' "
                    f"on {model_name} but the model does not have it",
                    hint="contribute_generated_columns() call missing or broken",
                    id="peeringdb_server.E101",
                )
            )

        leftover = {
            name
            for name in model_fields - declared
            if name.startswith("meta_") and name != "meta"
        }
        for name in sorted(leftover):
            errors.append(
                checks.Error(
                    f"{model_name} has metadata column '{name}' that no "
                    "registered key declares",
                    hint=(
                        "retiring a key must remove its generated column "
                        "(migration) along with the registry declaration"
                    ),
                    id="peeringdb_server.E102",
                )
            )

    return errors
